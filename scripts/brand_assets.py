"""Builds the Path.AI brand assets from the master logo PNG:  uv run --with pillow --with numpy --with potracer python scripts/brand_assets.py <logo.png>

The master is a 1000×1000 PNG (stacked lockup: the 'P' mark above the 'Path.AI' wordmark, white background).
Shapes are traced to vector (potrace) so the logo stays crisp from a 16 px favicon to a printed certificate;
colours are sampled from the master. Outputs go to src/static/brand/ (+ src/static/brand.js for inline use).
"""
import json
import sys
from pathlib import Path

import numpy as np
import potrace
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "src/static/brand"
NAVY, BLUE, BLUE_LIGHT = "#131734", "#4358fc", "#8fa2ff"
# diagonal gradient of the mark, bottom-left -> top-right (sampled from the master)
STOPS = [(0, "#1d27bf"), (0.5, "#3a4de6"), (0.85, "#6385fc"), (1, "#6b8efe")]


def trace(mask: np.ndarray, dx: float, dy: float) -> str:
    bm = potrace.Bitmap(~mask)  # potracer traces the False ("dark") pixels
    path = bm.trace(turdsize=6, turnpolicy=potrace.POTRACE_TURNPOLICY_MINORITY, alphamax=1.0, opticurve=True, opttolerance=0.2)
    f = lambda p: f"{p.x - dx:.1f} {p.y - dy:.1f}"
    d = []
    for curve in path:
        d.append(f"M{f(curve.start_point)}")
        for seg in curve:
            d.append(f"L{f(seg.c)}L{f(seg.end_point)}" if seg.is_corner else f"C{f(seg.c1)} {f(seg.c2)} {f(seg.end_point)}")
        d.append("Z")
    return "".join(d)


def bbox(mask):
    ys, xs = np.where(mask)
    return xs.min(), ys.min(), xs.max() + 1, ys.max() + 1


def main(master: str) -> None:
    img = Image.open(master).convert("RGB")
    px = np.asarray(img).astype(float)
    r, g, b = px[..., 0], px[..., 1], px[..., 2]
    ink = (255 - np.minimum(np.minimum(r, g), b)) > 110
    bluish = (b - r) > 60
    rows = ink.any(axis=1)
    gap = next(y for y in range(int(np.argmax(rows)), len(rows)) if not rows[y])  # first empty row below the mark
    mark_mask = ink.copy(); mark_mask[gap:] = False
    word_mask = ink.copy(); word_mask[:gap] = False
    mx0, my0, mx1, my1 = bbox(mark_mask)
    wx0, wy0, wx1, wy1 = bbox(word_mask)
    pad = 6
    mark_d = trace(mark_mask, mx0 - pad, my0 - pad)
    mw, mh = mx1 - mx0 + 2 * pad, my1 - my0 + 2 * pad
    navy_d = trace(word_mask & ~bluish, wx0 - pad, wy0 - pad)
    blue_d = trace(word_mask & bluish, wx0 - pad, wy0 - pad)
    ww, wh = wx1 - wx0 + 2 * pad, wy1 - wy0 + 2 * pad

    grad = "".join(f'<stop offset="{o}" stop-color="{c}"/>' for o, c in STOPS)
    defs = f'<defs><linearGradient id="pathai-g" x1="0" y1="1" x2="1" y2="0">{grad}</linearGradient></defs>'
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "mark.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {mw} {mh}">{defs}'
                                  f'<path fill="url(#pathai-g)" fill-rule="evenodd" d="{mark_d}"/></svg>\n')
    for name, navy in (("wordmark", NAVY), ("wordmark-light", "#ffffff")):
        blue = BLUE if navy == NAVY else BLUE_LIGHT
        (OUT / f"{name}.svg").write_text(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {ww} {wh}" role="img" aria-label="Path.AI">'
                                         f'<path fill="{navy}" fill-rule="evenodd" d="{navy_d}"/><path fill="{blue}" fill-rule="evenodd" d="{blue_d}"/></svg>\n')
    # stacked lockup, as in the master
    scale = 1.0
    lw = max(mw, ww)
    gap_px = (wy0 - my1)
    lh = mh + gap_px + wh
    (OUT / "logo.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {lw} {lh}" role="img" aria-label="Path.AI">{defs}'
        f'<path transform="translate({(lw - mw) / 2:.1f} 0)" fill="url(#pathai-g)" fill-rule="evenodd" d="{mark_d}"/>'
        f'<g transform="translate({(lw - ww) / 2:.1f} {mh + gap_px:.1f})"><path fill="{NAVY}" fill-rule="evenodd" d="{navy_d}"/>'
        f'<path fill="{BLUE}" fill-rule="evenodd" d="{blue_d}"/></g></svg>\n')
    (ROOT / "src/static/brand.js").write_text(
        "// Path.AI logo as vector data (generated by scripts/brand_assets.py from the master logo).\n"
        f"export const BRAND = {json.dumps({'mark': {'w': int(mw), 'h': int(mh), 'd': mark_d, 'stops': STOPS}, 'word': {'w': int(ww), 'h': int(wh), 'navy': navy_d, 'blue': blue_d, 'navyColor': NAVY, 'blueColor': BLUE}})};\n")

    # raster icons straight from the master pixels (exact colours), white background, wordmark blanked out
    icon_src = img.copy()
    icon_src.paste((255, 255, 255), (0, int(gap), icon_src.width, icon_src.height))

    def mark_square(size: int, margin: float) -> Image.Image:
        side = max(mx1 - mx0, my1 - my0)
        cx, cy = (mx0 + mx1) / 2, (my0 + my1) / 2
        half = side / 2 / (1 - 2 * margin)
        crop = icon_src.crop((int(cx - half), int(cy - half), int(cx + half), int(cy + half)))
        return crop.resize((size, size), Image.LANCZOS)
    mark_square(32, 0.04).save(OUT / "favicon-32.png", optimize=True)
    mark_square(180, 0.14).save(OUT / "apple-touch-icon.png", optimize=True)
    mark_square(512, 0.14).save(OUT / "icon-512.png", optimize=True)
    # link preview card: full stacked logo centred on white, 1200×630
    x0, y0, x1, y1 = bbox(ink)
    logo = img.crop((x0 - 20, y0 - 20, x1 + 20, y1 + 20))
    target_h = 470
    logo = logo.resize((int(logo.width * target_h / logo.height), target_h), Image.LANCZOS)
    card = Image.new("RGB", (1200, 630), "white")
    card.paste(logo, ((1200 - logo.width) // 2, (630 - logo.height) // 2))
    card.save(OUT / "og-image.png", optimize=True)
    print("brand assets written to", OUT)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else str(Path.home() / "Desktop/logoPathAi.png"))
